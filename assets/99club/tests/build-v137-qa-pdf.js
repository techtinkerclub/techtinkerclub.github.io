#!/usr/bin/env node
'use strict';

const fs=require('fs');
const path=require('path');
const ROOT=path.join(__dirname,'..');

// Load exactly the same generator / PDF layers as the live Games page.
require(path.join(ROOT,'games-arithmetic.js'));
require(path.join(ROOT,'games-number-logic.js'));
require(path.join(ROOT,'games-number-towers-v137.js'));
require(path.join(ROOT,'games-number-towers-v137-unique.js'));
require(path.join(ROOT,'games-number-path-v2.js'));
require(path.join(ROOT,'games-sumplete.js'));
const G=require(path.join(ROOT,'games-engine.js'));
require(path.join(ROOT,'games-puzzle-redesign-v135-logic.js'));
require(path.join(ROOT,'simple-pdf.js'));
require(path.join(ROOT,'games-pdf.js'));
require(path.join(ROOT,'games-pdf-v136.js'));
require(path.join(ROOT,'games-pdf-v137.js'));

const PDF=globalThis.TT99GamesPDF;
if(!PDF)throw new Error('PDF exporter failed to load');

const base=G.normalizeSettings({
  minYear:5,maxYear:6,
  topics:['number_place_value','calculation','geometry','algebra'],
  sheets:7,activitiesPerSheet:1,includeAnswers:true,workedExamples:'none',
  selectedEngines:['operationgrid','functionmachine','arithmagon','kakuro','numbertowers','symbols','balance'],
  personalisation:{schoolName:'99 Club Studio - visual QA',packTitle:'v1.37 Games & Puzzles QA Pack',classLabel:'Pupil / teacher review',worksheetDate:'',logoDataUrl:'',logoWidth:0,logoHeight:0}
});

function settingsFor(id,overrides={}){
  const s=JSON.parse(JSON.stringify(base));
  s.engineSettings[id]={...(s.engineSettings[id]||{}),...overrides};
  return s;
}
function valid(a,label){if(!a||a.error)throw new Error(`${label}: ${a?.error||'generation failed'}`);return a;}

// Pick a challenge Codebreaker that definitely exercises the multi-operation renderer.
let code=null;
for(let i=0;i<80;i++){
  const a=G.generateActivity('operationgrid',settingsFor('operationgrid',{difficulty:'challenge'}),`qa-v137-code-${i}`);
  if(a&&!a.error&&(a.rows||[]).some(r=>(String(r.text||'').match(/□/g)||[]).length>=2)){code=a;break;}
}
valid(code,'Operation Codebreaker');

const machine=valid(G.generateActivity('functionmachine',settingsFor('functionmachine',{difficulty:'challenge'}),'qa-v137-machine'),'Function Machine');
const arith=valid(G.generateActivity('arithmagon',settingsFor('arithmagon',{difficulty:'challenge',shape:'square',operation:'mixed_within',connections:'diagonals',missing:'balanced'}),'qa-v137-arithmagon'),'Arithmagon');
const kakuro=valid(G.generateActivity('kakuro',settingsFor('kakuro',{difficulty:'challenge',gridSize:'8',givenLevel:'minimum'}),'qa-v137-kakuro8'),'8x8 Kakuro');
const towers=valid(G.generateActivity('numbertowers',settingsFor('numbertowers',{difficulty:'challenge',gridSize:'6',clueLevel:'fewer'}),'qa-v137-towers'),'Number Towers');
const symbols=valid(G.generateActivity('symbols',settingsFor('symbols',{difficulty:'challenge',symbolCount:'3',equationStyle:'coefficients'}),'qa-v137-symbols'),'Symbol Equations');
const repair=valid(G.generateActivity('balance',settingsFor('balance',{difficulty:'challenge'}),'qa-v137-repair'),'Equation Repair');

// One activity per pupil page deliberately gives every redesigned visual room to breathe.
// The matching answer pages are generated by the same exporter immediately afterwards.
const activities=[code,machine,arith,kakuro,towers,symbols,repair];
const pack={version:'1.37-QA',seed:'v137-visual-qa',settings:base,workedExamples:[],sheets:activities.map((a,i)=>({index:i+1,activities:[a]}))};
const doc=PDF.buildDocument({pack,settings:base,topics:G.TOPICS,seed:pack.seed,kind:'both'});
const bytes=doc.outputBytes();
const outDir=path.resolve(process.cwd(),'artifacts');
fs.mkdirSync(outDir,{recursive:true});
const out=path.join(outDir,'v137-games-qa-pack.pdf');
fs.writeFileSync(out,Buffer.from(bytes));
console.log(`Wrote ${out} (${bytes.length} bytes, ${doc.pages.length} pages)`);
console.log('Activities:',activities.map(a=>`${a.title} [${a.difficulty}]`).join(' | '));
