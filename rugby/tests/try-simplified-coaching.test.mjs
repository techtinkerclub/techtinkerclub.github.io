import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {calloutOverlay,cleanCallouts} from '../js/comic-callouts.js';
import {tryLineEvents,tryCelebrationAt,RUCKUS_TRY_CELEBRATION_SECONDS,TRY_GROUND_HOLD_SECONDS} from '../js/try-scoring.js';
import {playbackData,renderScene} from '../js/scene.js';
import {drillGeometry} from '../js/pitch.js';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const editor=JSON.parse(read('data/coach-drills.json')).drills.find(d=>d.id==='u10-3v2-overload-to-try-v1');
const published=JSON.parse(read('data/published-drills.json')).drills.find(d=>d.id==='seed-923');
test('try drill teaches with one anchored and readable cue, not two competing bubble styles',()=>{
 assert(editor&&published);
 assert.deepEqual(editor.frames,published.frames);
 assert.equal(editor.frames[4].callouts?.length||0,0,'Crossing only is conveyed by the step name and narration');
 const cue=editor.frames[5].callouts;
 assert.equal(cue.length,1);
 assert.equal(cue[0].text,'GROUND IT!');
 assert.equal(cue[0].kind,'speech');
 assert.equal(cue[0].anchorMode,'fixed');
 assert(cue[0].displaySeconds>=1.2);
 assert(editor.frames[5].seconds>=2);
 assert.equal(editor.frames[5].tryGroundings[0].at,.78);
});
test('fixed authored cue stays in one place even while the ball carrier moves',()=>{
 const actor={id:'a1',type:'attacker',x:500,y:200,label:'A1'};
 const frames=[{seconds:0,objects:[actor]},{seconds:2,objects:[actor],callouts:[{id:'cue',actorId:'a1',text:'GROUND IT!',kind:'speech',anchorMode:'fixed',at:0,displaySeconds:2}]}];
 cleanCallouts(frames[1]);
 assert.equal(frames[1].callouts[0].anchorMode,'fixed');
 const g={margin:42,viewWidth:900,viewHeight:540,toView:(x,y)=>({x,y})};
 const a=calloutOverlay(frames,1,[{...actor,x:490,y:245}],g,.25,{cartoonMode:true});
 const b=calloutOverlay(frames,1,[{...actor,x:650,y:365}],g,.85,{cartoonMode:true});
 assert.equal(a,b,'The bubble does not jump between orientations as its author moves');
});
test('grounding stays visible before rising and true celebration uses approved atlas poses',()=>{
 const d=playbackData(published),g=drillGeometry(d,'up');
 const events=tryLineEvents(d,g);
 assert.equal(events.length,1);
 const t=events[0].time;
 assert(TRY_GROUND_HOLD_SECONDS>=.85,'Grounding needs a meaningful teaching hold');
 assert(RUCKUS_TRY_CELEBRATION_SECONDS>=2.5,'Leave time for rise and arms-up celebration');
 assert.equal(tryCelebrationAt(events,t+.75,events[0].actorId).phase,'ground');
 assert.equal(tryCelebrationAt(events,t+1.12,events[0].actorId).phase,'rise');
 assert.equal(tryCelebrationAt(events,t+1.8,events[0].actorId).phase,'celebrate');
 const prone=renderScene(d,{time:t+.75,cartoonMode:true}).svg;
 assert.match(prone,/data-try-celebration="ground"/);
 assert.match(prone,/data-ruckus-pose="present-prone"/);
 const cheer=renderScene(d,{time:t+1.8,cartoonMode:true}).svg;
 assert.match(cheer,/data-try-celebration="celebrate"/);
 assert.match(cheer,/data-ruckus-pose="5[23]"/);
 const classic=renderScene(d,{time:t+1.8,cartoonMode:false}).svg;
 assert.doesNotMatch(classic,/data-try-celebration="celebrate"/);
});
test('ready tackle donut has inspector nudges that ripple into later stationary frames',()=>{
 const src=read('js/app.js');
 assert.match(src,/className='donut-start-nudge'/);
 assert.match(src,/data-donut-nudge=/);
 assert.match(src,/propagatePosition\(drill\.frames,idx,o\.id,old,'onward'\)/);
 assert.match(src,/Math\.hypot\(target\.x-o\.x,target\.y-o\.y\)/);
});
