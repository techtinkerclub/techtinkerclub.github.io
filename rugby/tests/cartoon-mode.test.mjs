assert.equal((classic.match(/M-5 -12 L0 -19 L5 -12 Z/g)||[]).length,0,'Old fixed body arrow must be removed');
assert.doesNotMatch(classic,/cartoon-player-eyes|goggle/,'Classic view cannot show cartoon eyes');
assert.match(cartoon,/ruckus-player/,'Approved red Ruckus player is rendered');
assert.match(cartoon,/data-ruckus-pose="0"/,'Standing look-right uses original standing1 sprite');
assert.match(cartoon,/cartoon-player/);
assert.doesNotMatch(cartoon,/player-gaze-arrow|M-5 -12 L0 -19 L5 -12 Z/,'No direction arrow in cartoon mode');
assert.match(cartoon,/rugby-ruckus-blue-54/,'Attackers use approved blue 54-pose atlas');
const another={...player,id:'a2'};
const alternate=playerAppearance(another,'standing',original,[another,defender],view,null,null,1,{cartoonMode:true});
assert.equal(cartoon,alternate,'Same pose and team use the same sprite artwork');
const defended=playerAppearance(defender,'standing',original,[player,defender],view,null,null,1,{cartoonMode:true});
assert.match(defended,/ruckus-player/,'Defenders use approved artwork');
assert.match(defended,/data-ruckus-team="red"/,'Defenders retain the red kit');
assert.match(defended,/rugby-ruckus-red-54/,'Defenders reference user-supplied 54-pose atlas');
assert.match(cartoon,/data-ruckus-team="blue"/,'Attackers get blue kit');
assert.doesNotMatch(cartoon,/ruckus-team-blue-v2/,'Use real pre-recoloured blue atlas, not an SVG filter');
assert.doesNotMatch(defended,/rugby-ruckus-blue-54/,'Defender uses red atlas only');
const tacklePose=playerAppearance({...defender,playerPose:'tackling'},'tackling',original,[defender],view,null,null,1,{cartoonMode:true});
assert.match(tacklePose,/ruckus-player/,'Tackle uses Ruckus artwork');
assert.match(tacklePose,/data-ruckus-pose="32"/,'Tackle contact progresses through user tackleapp1-6 sprites');
assert.doesNotMatch(cartoon,/data-ruckus-pose="32"/,'Neutral pose does not look like a tackle');
const approach=playerAppearance(defender,'tackling',original,[defender],view,null,null,.1,{cartoonMode:true});
assert.match(approach,/data-ruckus-pose="27"/,'Early tackle uses original tackleapp1');
assert.match(defended,/data-ruckus-pose="2"/,'Defender forward idle uses original standing3');
const runningBefore={objects:[{...player,x:100,y:120}],timing:{},paths:{}};
const runningAfter={objects:[{...player,x:100,y:200}],seconds:2,timing:{},paths:{}};
const running=playerAppearance(player,'standing',original,[player,defender],view,runningBefore,runningAfter,.5,{cartoonMode:true});
assert.match(running,/data-ruckus-pose="1[0-4]"/,'Running uses one of five original sprinting poses');
assert.notEqual(running,cartoon,'Running is not a standing sprite');
for(const [pose,expected] of [['held',24],['ready',26],['recovering',41],['grounded',35]]){
 const result=playerAppearance(defender,pose,original,[defender],view,null,null,1,{cartoonMode:true});
 assert.match(result,new RegExp('data-ruckus-pose="'+expected+'"'),'Ruckus pose '+pose+' maps to a real uploaded image');
}

const onGround=playerAppearance(defender,'grounded',original,[defender],view,null,null,1,{cartoonMode:true});
assert.match(onGround,/data-ruckus-pose="35"/,'Grounded player uses user tackled3 sprite');
assert.doesNotMatch(onGround,/data-ruckus-pose="42"/,'Do not use crouched present.png as lying down');
const contact={id:'t1',type:'tackle',breakdown:{phase:'tackle'},members:[{id:'a1',pose:'grounded'},{id:'d1',pose:'tackling'}],x:130,y:120};
const heldStep={objects:[player,defender,contact],seconds:2};
const groundedCarrier=playerAppearance(player,'grounded',original,[player,defender,contact],view,heldStep,heldStep,1,{cartoonMode:true});
const completingTackler=playerAppearance(defender,'tackling',original,[player,defender,contact],view,heldStep,heldStep,1,{cartoonMode:true});
assert.match(groundedCarrier,/data-ruckus-pose="35"/,'Carrier stays on the floor after contact');
assert.match(completingTackler,/data-ruckus-pose="32"/,'Tackler stays in final contact pose, not replaying approach');
const presentedBall={id:'b1',type:'ball',x:105,y:125,transferKind:'presentation',groundState:'presented'};
const presentingStep={objects:[player,defender,contact,presentedBall],seconds:2};
const beforePresent={objects:[player,defender,contact,{...presentedBall,ownerId:player.id,transferKind:'pass',groundState:'grounded'}],seconds:2};
const presenting=playerAppearance(player,'grounded',original,[player,defender,contact,presentedBall],view,beforePresent,presentingStep,1,{cartoonMode:true});
assert.match(presenting,/data-ruckus-pose="present-prone"/,'Present on the ground using new ball-free prone image');
assert.match(presenting,/rugby-ruckus-presentation-v1/,'Ruckus presentation uses dedicated sprite asset');
assert.match(presenting,/data-ruckus-presentation-bearing="135.0"/,'Player turns towards real authored ball');
const leftBall={...presentedBall,x:69,y:120};
const rightBall={...presentedBall,x:132,y:120};
for(const [ball,bearing,rotation] of [[leftBall,'-90.0','0.0'],[rightBall,'90.0','180.0']]){
 const prev={objects:[player,{...ball,ownerId:player.id,groundState:'grounded'}],seconds:2};
 const current={objects:[player,ball],seconds:2};
 const svg=playerAppearance(player,'grounded',original,[player,ball],view,prev,current,1,{cartoonMode:true});
 assert.match(svg,new RegExp('data-ruckus-presentation-bearing="'+bearing+'"'),'Presentation follows the actual ball side');
 assert.match(svg,new RegExp('rotate\\('+rotation+' 64 64\\)'),'Ball-side orientation rotates the PRONE artwork');
}
const redBall={...presentedBall,x:126,y:120};
const prevRed={objects:[defender,{...redBall,ownerId:defender.id,groundState:'grounded'}],seconds:2};
const redSvg=playerAppearance(defender,'grounded',original,[defender,redBall],view,prevRed,{objects:[defender,redBall],seconds:2},1,{cartoonMode:true});
assert.match(redSvg,/data-ruckus-pose="present-prone"/,'Defenders use the same presentation stance');
assert.match(redSvg,/rugby-ruckus-presentation-v1/,'Red sprite references the same recoloured asset');
