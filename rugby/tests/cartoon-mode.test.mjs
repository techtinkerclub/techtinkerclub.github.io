const view={toView:(x,y)=>({x,y}),rotation:0,viewWidth:900,viewHeight:540};
const player={id:'a1',type:'attacker',label:'A1',x:100,y:120,rot:0,headMode:'player',headTargetId:'d1'};
const defender={id:'d1',type:'defender',label:'D1',x:160,y:120,rot:180};
