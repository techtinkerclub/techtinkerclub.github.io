import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {blank} from '../js/model.js';
import {playerAppearance,cartoonPitchDecor} from '../js/cartoon-players.js';
import {renderScene,playbackData} from '../js/scene.js';
import {outputOptions} from '../js/outputs.js';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const view={toView:(x,y)=>({x,y}),rotation:0,viewWidth:900,viewHeight:540};
const player={id:'a1',type:'attacker',label:'A1',x:100,y:120,rot:0,headMode:'player',headTargetId:'d1'};
const defender={id:'d1',type:'defender',label:'D1',x:160,y:120,rot:180};
const original='<circle r="15" fill="#75c9ff"/><path d="M-5 -12 L0 -19 L5 -12 Z" fill="#f7fff6"/>';
const classic=playerAppearance(player,'standing',original,[player,defender],view,null,null,1,{cartoonMode:false});
const cartoon=playerAppearance(player,'standing',original,[player,defender],view,null,null,1,{cartoonMode:true});
assert.match(classic,/player-gaze-arrow/);
assert.equal((classic.match(/M-5 -12 L0 -19 L5 -12 Z/g)||[]).length,0,'Old fixed body arrow must be removed');
assert.doesNotMatch(classic,/cartoon-player-eyes|goggle/,'Classic view cannot show cartoon eyes');
assert.match(cartoon,/minion-independent-head/,'Original layered overhead sprite is present');
assert.match(cartoon,/minion-rig-player/,'Original detailed atlas sprites are restored');
assert.match(cartoon,/cartoon-player/);
assert.doesNotMatch(cartoon,/player-gaze-arrow|M-5 -12 L0 -19 L5 -12 Z/,'No direction arrow in cartoon mode');
assert.match(cartoon,/rugby-minion-head-v9/,'Original sprite head asset is used');
const another={...player,id:'a2'};
const alternate=playerAppearance(another,'standing',original,[another,defender],view,null,null,1,{cartoonMode:true});
assert.equal(cartoon,alternate,'Same pose and team use the same sprite artwork');
const defended=playerAppearance(defender,'standing',original,[player,defender],view,null,null,1,{cartoonMode:true});
assert.notEqual(cartoon,defended,'Different teams use distinct atlas art');
const tacklePose=playerAppearance({...defender,playerPose:'tackling'},'tackling',original,[defender],view,null,null,1,{cartoonMode:true});
assert.match(tacklePose,/minion-tackle-arms/,'Tackling adds forward wrapping arms');
assert.match(tacklePose,/data-tackle-phase="ready"/,'Standalone tackle is contact-ready');
assert.doesNotMatch(cartoon,/minion-tackle-arms/,'Standing is not accidentally given tackle arms');
assert.doesNotMatch(defended,/minion-tackle-arms/,'Defender idle pose stays unchanged');
assert.equal(playerAppearance({id:'ball',type:'ball'},'standing',original,[],view,null,null,1,{cartoonMode:true}),original,'Non-player objects must not be restyled');
assert.match(cartoonPitchDecor(view),/cartoon-pitch-decor/);
const d=blank();d.frames[0].objects=[player,defender];
const base=renderScene(playbackData(d),{index:0,cartoonMode:false});
const fun=renderScene(playbackData(d),{index:0,cartoonMode:true});
assert.match(base.svg,/player-gaze-arrow/);
assert.doesNotMatch(base.svg,/cartoon-pitch-decor/);
assert.match(fun.svg,/minion-rig-player/);
assert.doesNotMatch(fun.svg,/player-gaze-arrow/);
assert.match(fun.svg,/cartoon-pitch-decor/);
assert.equal(outputOptions({cartoonMode:true}).cartoonMode,true);
assert.equal(outputOptions({}).cartoonMode,false);
assert.deepEqual(playbackData(d),playbackData(d),'Visual theme must not modify source drill');
const editor=read('index.html'),play=read('play.html'),app=read('js/app.js'),playerJS=read('js/player.js');
assert.match(editor,/id="minionMode"/);
assert.match(play,/id="playerMinionMode"/);
assert.match(app,/\$\('minionMode'\)\.onclick/);
assert.match(playerJS,/\$\('playerMinionMode'\)\.onclick/);
assert.match(app,/cartoonMode\?cartoonPitchDecor/);
assert.match(app,/function shareOptions\(\)\{return outputOptions\(\{orientation,scaleMode,cartoonMode/);
assert.match(read('assets/workspace.css'),/\.pitch-cartoon-toggle/);
assert.match(read('assets/player-responsive.css'),/\.presentation-pitch-shell/);
