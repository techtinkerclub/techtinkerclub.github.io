import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {blank} from '../js/model.js';
import {playbackData,renderScene} from '../js/scene.js';
import {addInteraction,hydrateLegacyTagItems,outstandingTagItems,timedSkillObjects,skillIcon,sanitizeInteractions} from '../js/skill-actions.js';

const d=blank();d.title='Call, pass and return';d.ageMin=8;d.ageMax=8;
const setup=[
 {id:'carrier',type:'attacker',label:'A1',x:395,y:290,rot:0,tagBelt:true,tagColor:'yellow',tags:{left:true,right:true},heldTags:0},
 {id:'tagger',type:'defender',label:'D1',x:415,y:270,rot:180,tagBelt:true,tagColor:'blue',tags:{left:true,right:true},heldTags:0},
 {id:'ball',type:'ball',label:'Ball',x:395,y:290,rot:0,ownerId:'carrier'}
];
const frame=(name,objects)=>({name,seconds:2,notes:'',timing:{},paths:{},objects:structuredClone(objects)});
d.frames[0].objects=structuredClone(setup);
const tagged=frame('TAG!',setup);
const take=addInteraction(tagged,'tag','tagger','carrier','left','');
assert.equal(take.ok,true,take.message);tagged.interactions[0].at=.45;
assert.equal(tagged.objects[0].tags.left,false);
assert.equal(tagged.objects[1].heldTagItems.length,1);
assert.equal(tagged.objects[1].heldTagItems[0].targetId,'carrier');
assert.equal(tagged.objects[1].heldTagItems[0].side,'left');
assert.equal(tagged.objects[1].heldTagItems[0].color,'yellow');
assert.equal(outstandingTagItems(tagged).length,1);
assert.match(skillIcon(tagged.objects[1]),/tag-belt/);
assert.match(skillIcon(tagged.objects[1]),/#f5d56b/,'The raised stolen strip uses the carrier strip colour');
const beforeTake=timedSkillObjects(tagged.objects,d.frames[0],tagged,.2);
const afterTake=timedSkillObjects(tagged.objects,d.frames[0],tagged,.65);
assert.equal(beforeTake[0].tags.left,true);
assert.equal(beforeTake[1].heldTagItems.length,0);
assert.equal(afterTake[0].tags.left,false);
assert.equal(afterTake[1].heldTagItems.length,1);
const valid=JSON.parse(JSON.stringify(tagged));sanitizeInteractions(valid);
assert.equal(valid.interactions[0].kind,'tag');
d.frames.push(tagged);
const returned=frame('Return tag',tagged.objects);
const giveBack=addInteraction(returned,'tag-return','tagger','carrier','left','');
assert.equal(giveBack.ok,true,giveBack.message);returned.interactions[0].at=.8;
assert.equal(returned.objects[0].tags.left,true);
assert.equal(returned.objects[1].heldTagItems.length,0);
assert.equal(returned.objects[1].heldTags,0);
assert.equal(outstandingTagItems(returned).length,0);
assert.equal(addInteraction(returned,'tag-return','tagger','carrier','left').ok,false,'Cannot return the same tag twice');
const earlyReturn=timedSkillObjects(returned.objects,tagged,returned,.5);
const completedReturn=timedSkillObjects(returned.objects,tagged,returned,.9);
assert.equal(earlyReturn[0].tags.left,false);
assert.equal(earlyReturn[1].heldTagItems.length,1);
assert.equal(completedReturn[0].tags.left,true);
assert.equal(completedReturn[1].heldTagItems.length,0);
d.frames.push(returned);
const clean=playbackData(d);
assert.equal(clean.frames[1].objects.find(o=>o.id==='tagger').heldTagItems[0].targetId,'carrier');
assert.equal(clean.frames[2].objects.find(o=>o.id==='tagger').heldTagItems.length,0);
assert.equal(clean.frames[2].interactions[0].kind,'tag-return');
const takeSVG=renderScene(clean,{index:1}).svg,returnSVG=renderScene(clean,{index:2}).svg;
assert.match(takeSVG,/TAG!/,'Shout visible after tag removal');
assert.match(takeSVG,/non-contact-actions/);
assert.match(takeSVG,/#f5d56b/);
assert.match(returnSVG,/TAG RETURNED/);
const legacy=frame('Old tag recording',setup);
legacy.interactions=[{kind:'tag',actorId:'tagger',targetId:'carrier',side:'right',at:.5,label:'Tag removed'}];
legacy.objects.find(o=>o.id==='carrier').tags.right=false;
legacy.objects.find(o=>o.id==='tagger').heldTags=1;
hydrateLegacyTagItems([frame('Setup',setup),legacy]);
assert.deepEqual(legacy.objects.find(o=>o.id==='tagger').heldTagItems,[{targetId:'carrier',side:'right',color:'yellow'}]);
assert.equal(outstandingTagItems(legacy).length,1);
const app=readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.match(html,/value="tag-return"/);
assert.match(app,/openSkillDialog\('tag-return'/);
assert.match(app,/Return tag/);
assert.match(app,/action\.kind==='tag-return'/,'Return action can be removed with original state restored');
