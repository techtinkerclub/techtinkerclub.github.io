import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {playerHeadAngle,playerHeadSVG,headSettings} from '../js/player-gaze.js';
import {addInteraction,sanitizeInteractions,interactionOverlay} from '../js/skill-actions.js';
import {blank} from '../js/model.js';
import {playbackData,renderScene} from '../js/scene.js';

const g={toView:(x,y)=>({x,y}),fromView:(x,y)=>({x,y}),rotation:0};
const a={id:'a',type:'attacker',label:'A1',rot:0,x:100,y:100};
const b={id:'b',type:'attacker',label:'A2',rot:0,x:200,y:100};
const defender={id:'d',type:'defender',label:'D1',rot:0,x:115,y:105};
const current={objects:[a,b,defender],seconds:2,timing:{},paths:{}};
assert.equal(headSettings(a).mode,'run','Follow run is default, with no migration required');
assert.equal(playerHeadAngle({...a,headMode:'forward'},current.objects,g),0,'Look forward means do not follow anything');
assert.equal(playerHeadAngle({...a,headMode:'player',headTargetId:'b'},current.objects,g),90,'Track player independently from body');
assert.match(playerHeadSVG({...a,headMode:'player',headTargetId:'b'},current.objects,g),/rotate\(90\.0\)/);
assert.equal(playerHeadAngle({...a,playerPose:'grounded'},current.objects,g),null,'Grounded players should not wear a floating tracking head');
const previousRun={objects:[{...a,x:30,y:100},b,defender]};
assert.equal(playerHeadAngle(a,current.objects,g,previousRun,current,.5),90,'Head follows an authored run by default');
const tackle={...current,objects:[...current.objects,{id:'tackle',type:'tackle',members:[{id:'a',pose:'grounded'},{id:'d',pose:'tackling'}],breakdown:{carrierId:'a'}}]};
assert.ok(playerHeadAngle({...defender,headMode:'forward'},tackle.objects,g,previousRun,tackle,.5)<0,'Tackler must look towards ball carrier even when locked straight ahead');
const passingBefore={objects:[a,b,{id:'ball',type:'ball',ownerId:'a',x:100,y:100}]};
const passingAfter={objects:[a,b,{id:'ball',type:'ball',ownerId:'b',x:200,y:100,transferKind:'pass'}],timing:{ball:{start:45,end:75}}};
assert.equal(playerHeadAngle({...a,headMode:'forward'},passingAfter.objects,g,passingBefore,passingAfter,.28),90,'Look at receiver before a pass overrides user head mode');
assert.equal(playerHeadAngle({...a,headMode:'forward'},passingAfter.objects,g,passingBefore,passingAfter,.85),0,'Head returns to manual mode after release');

const player={id:'carrier',type:'attacker',label:'Carrier',x:200,y:200,tagBelt:true,tags:{left:true,right:true}};
const tagger={id:'tagger',type:'defender',label:'Tagger',x:240,y:200,tagBelt:true,tags:{left:true,right:true}};
const ball={id:'ball',type:'ball',ownerId:'carrier',x:200,y:200};
const step0={seconds:0,objects:[structuredClone(player),structuredClone(tagger),structuredClone(ball)]};
const step1={seconds:2,objects:[structuredClone(player),structuredClone(tagger),structuredClone(ball)]};
assert.equal(addInteraction(step1,'tag','tagger','carrier','left').ok,true);
step1.interactions[0].at=.7;step1.interactions[0].displaySeconds=1.6;
sanitizeInteractions(step1);
assert.equal(step1.interactions[0].displaySeconds,1.6);
const step2={seconds:2,objects:structuredClone(step1.objects)};
const frames=[step0,step1,step2];
const visual=progress=>interactionOverlay(step2,step2.objects,g,progress,false,{frames,index:2});
assert.match(visual(.2),/TAG!/,'Callout remains into next step');
assert.doesNotMatch(visual(.7),/TAG!/,'Callout disappears at its authored duration');
const before=interactionOverlay(step1,step1.objects,g,.65,false,{frames,index:1});
const during=interactionOverlay(step1,step1.objects,g,.8,false,{frames,index:1});
assert.doesNotMatch(before,/TAG!/);
assert.match(during,/TAG!/);
step1.interactions[0].displaySeconds=.2;
assert.doesNotMatch(visual(.2),/TAG!/,'Shorter duration changes playback');
const drill=blank();drill.frames=[{...drill.frames[0],objects:structuredClone(step0.objects)},step1,step2];
const clean=playbackData(drill);
assert.equal(clean.frames[1].interactions[0].displaySeconds,.2,'Display duration survives publishing');
assert.match(renderScene(clean,{index:1}).svg,/player-head-gaze/,'Read-only output contains head graphics');
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const app=read('js/app.js'),html=read('index.html'),scene=read('js/scene.js');
assert.match(html,/id="skillDuration"/);
assert.match(app,/data-callout-seconds/);
assert.match(app,/appendHeadInspector\(o,disabled\)/);
assert.match(app,/playerHeadSVG\(/);
assert.match(scene,/playerHeadSVG\(/);
assert.match(scene,/headTargetId/);
assert.match(app,/frames:drill\.frames,index:lineIndex/);
assert.match(scene,/frames:d\.frames,index:i/);
